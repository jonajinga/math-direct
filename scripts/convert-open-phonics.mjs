// One-time conversion of the Open Phonics data into source files under
// curriculum/reading/. Run again only to refresh them from a checkout of
// github.com/jonajinga/open-phonics:
//   node scripts/convert-open-phonics.mjs /path/to/open-phonics
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tokensFor } from "../curriculum/reading/tokens.js";
const src = process.argv[2];
if (!src) { console.error("usage: node scripts/convert-open-phonics.mjs <open-phonics checkout>"); process.exit(2); }
const words = (await import(join(src, "src/_data/wordList.js"))).default;
const lessons = (await import(join(src, "src/_data/lessons.js"))).default;

// ── Words ──
// Each word keeps its first lesson, its sound groups, and whether it is read
// whole (an irregular word). Duplicates keep the earliest lesson.
const byWord = new Map();
for (const w of words) {
  const key = w.word;
  // A word is read whole when it is marked as one, or when its sounds cannot
  // be laid over its spelling by the rules the child has.
  const irregular = /trick word|sight word/i.test(w.note || "") || !tokensFor(w.word, w.sounds || []);
  const prev = byWord.get(key);
  if (!prev || w.lesson < prev.lesson) byWord.set(key, { word: w.word, lesson: w.lesson, sounds: w.sounds || [], irregular });
}
const list = [...byWord.values()].sort((a, b) => a.lesson - b.lesson || a.word.localeCompare(b.word));
let out = "// The words of the reading program, from the Open Phonics word list: each\n// with the lesson it is first read in, its sound groups, and whether it is\n// read whole (an irregular word). Generated by scripts/convert-open-phonics.mjs;\n// edit by hand after that.\n\nexport default [\n";
for (const w of list) out += `  { word: ${JSON.stringify(w.word)}, lesson: ${w.lesson}, sounds: ${JSON.stringify(w.sounds)}${w.irregular ? ", irregular: true" : ""} },\n`;
out += "];\n";
writeFileSync("curriculum/reading/words.js", out);
console.log("words:", list.length, "irregular:", list.filter((w) => w.irregular).length);

// ── Sentences ──
// Sentences the lessons showed, kept where every word is in the list, and
// placed at the first lesson where every word has been taught.
const first = new Map();
for (const w of list) { const k = w.word.toLowerCase(); if (!first.has(k) || w.lesson < first.get(k)) first.set(k, w.lesson); }
const strip = (h) => String(h || "").replace(/<[^>]*>/g, "").replace(/\s+/g, " ").trim();
const seen = new Set();
const sents = [];
for (const l of lessons) {
  for (const s of l.steps) {
    const text = strip(s.display);
    if (!/\s/.test(text) || text.length >= 140 || seen.has(text)) continue;
    const toks = text.toLowerCase().match(/[a-z']+/g) || [];
    if (toks.some((t) => !first.has(t))) continue;
    const readableAt = Math.max(l.id, ...toks.map((t) => first.get(t)));
    seen.add(text);
    sents.push({ lesson: readableAt, text });
  }
}
sents.sort((a, b) => a.lesson - b.lesson);
let out2 = "// Sentences from the Open Phonics lessons, each placed at the first lesson\n// where every word in it has been taught. Generated by\n// scripts/convert-open-phonics.mjs; edit by hand after that.\n\nexport default [\n";
for (const s of sents) out2 += `  { lesson: ${s.lesson}, text: ${JSON.stringify(s.text)} },\n`;
out2 += "];\n";
writeFileSync("curriculum/reading/sentences.js", out2);
console.log("sentences:", sents.length, "| by lesson 100:", sents.filter((s) => s.lesson <= 100).length, "| first:", JSON.stringify(sents.slice(0, 5)));

// ── Stories ──
// The thirty stories, each as its title, its sentences (one to a line on the
// stage), and the questions asked after it. Bold marks and the word lists
// in the files are dropped: the program places each story by the words it
// uses. Written as plain data, with no markup.
import { readdirSync } from "node:fs";
const storyDir = join(src, "src/stories");
const stories = [];
for (const f of readdirSync(storyDir).filter((x) => x.endsWith(".md")).sort()) {
  const raw = readFileSync(join(storyDir, f), "utf8");
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) continue;
  const [, fm, body] = m;
  const field = (k) => { const r = fm.match(new RegExp("^" + k + ":\\s*(.+)$", "m")); return r ? r[1].trim().replace(/^"|"$/g, "") : ""; };
  const questions = [];
  const qre = /- q:\s*"([^"]*)"\s*\n\s*a:\s*"([^"]*)"/g;
  let q;
  while ((q = qre.exec(fm))) questions.push({ q: q[1], a: q[2] });
  const text = body.replace(/\*\*/g, "").replace(/[\u201c\u201d]/g, '"').replace(/[\u2018\u2019]/g, "'").replace(/\s+/g, " ").trim();
  // One sentence to a line; a closing quotation mark stays with its sentence.
  // A sentence of more than twelve words breaks at the comma nearest its middle.
  const lines = text.match(/[^.!?]+[.!?]+"?/g).map((x) => x.trim()).filter(Boolean).flatMap((l) => {
    if (l.split(" ").length <= 12 || !l.includes(", ")) return [l];
    const words = l.split(" ");
    let best = -1;
    words.forEach((w, i) => { if (w.endsWith(",") && (best < 0 || Math.abs(i - words.length / 2) < Math.abs(best - words.length / 2))) best = i; });
    return best < 0 ? [l] : [words.slice(0, best + 1).join(" "), words.slice(best + 1).join(" ")];
  });
  stories.push({ slug: f.replace(/\.md$/, ""), title: field("title"), phase: Number(field("phase")), order: Number(field("order")), lines, questions });
}
stories.sort((a, b) => a.order - b.order);
let out3 = "// The stories, from Open Phonics: the title, the lines (one sentence each),\n// and the questions asked after the second reading. Generated by\n// scripts/convert-open-phonics.mjs; edit by hand after that. The lesson each\n// story can be read at is worked out from its words when the level is built.\n\nexport default [\n";
for (const st of stories) {
  out3 += `  {\n    slug: ${JSON.stringify(st.slug)}, title: ${JSON.stringify(st.title)}, order: ${st.order},\n    lines: [\n${st.lines.map((l) => "      " + JSON.stringify(l) + ",\n").join("")}    ],\n    questions: [\n${st.questions.map((x) => "      " + JSON.stringify(x) + ",\n").join("")}    ],\n  },\n`;
}
out3 += "];\n";
writeFileSync("curriculum/reading/stories.js", out3);
console.log("stories:", stories.length, "| lines:", stories.reduce((a, s) => a + s.lines.length, 0), "| questions:", stories.reduce((a, s) => a + s.questions.length, 0), "| longest line:", Math.max(...stories.flatMap((s) => s.lines.map((l) => l.split(" ").length))));
